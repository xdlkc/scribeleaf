import Foundation

/// Localizes the app's menu labels. Product and theme names retain their names.
func localizedMenuTitle(_ english: String) -> String {
    guard let preferredLanguage = Locale.preferredLanguages.first else { return english }
    let parts = preferredLanguage.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-")
    guard parts.first == "zh", !parts.contains("hant"),
          parts.contains("hans") || parts.contains("cn") || parts.contains("sg") else { return english }

    // Keep the menu's ellipsis, which indicates that the command opens a dialog.
    let hasEllipsis = english.hasSuffix("…") || english.hasSuffix("...")
    let key = english.hasSuffix("…") ? String(english.dropLast())
        : english.hasSuffix("...") ? String(english.dropLast(3)) : english
    guard let translation = simplifiedChineseMenuTitles[key] else { return english }
    return translation + (hasEllipsis ? "…" : "")
}

