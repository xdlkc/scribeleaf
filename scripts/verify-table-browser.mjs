import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
const cli=process.env.AGENT_BROWSER||'/Users/lkc/.npm/_npx/ad6c181e5b604bdb/node_modules/.bin/agent-browser';
const run=(...args)=>execFileSync(cli,['--session','typora-qa',...args],{encoding:'utf8',timeout:30000});
const evaluate=code=>JSON.parse(execFileSync(cli,['--session','typora-qa','eval','--stdin'],{input:code,encoding:'utf8',timeout:30000}));
const results=[];
const check=(name,code)=>{try{const detail=evaluate(code);results.push({name,passed:detail.ok,detail});}catch(e){results.push({name,passed:false,detail:e.message});}};
const source='# Tables\n\nOUTSIDE_BEFORE\n\n| Name | Value |\n| :--- | ---: |\n| **bold** | first |\n| 中文 | `a|b` |\n\nOUTSIDE_AFTER\n';
run('open',process.env.APP_URL||'http://127.0.0.1:5174');
run('wait','--fn','Boolean(window.typora?.editor)');
evaluate(`(()=>{window.typora.command('load',{markdown:${JSON.stringify(source)},path:'',name:'table.md'});return true})()`);
try {
  run('click','.lp-cell[data-row="1"][data-col="1"]');
  run('click','.cm-header-1');
  check('Focus and blur do not rewrite the table',`({ok:window.typora.getMarkdown()===${JSON.stringify(source)}})`);
  run('click','.lp-cell[data-row="1"][data-col="1"]');
  evaluate(`(()=>{window.__tableCell=document.activeElement;return true})()`);
  run('press','Meta+a');
  run('keyboard','inserttext','alpha中文');
  check('Cell edit reaches source immediately and keeps other bytes',`({ok:window.typora.getMarkdown()===${JSON.stringify(source.replace('first','alpha中文'))},text:window.typora.getMarkdown()})`);
  check('Typing preserves the focused DOM cell',`({ok:document.activeElement===window.__tableCell&&window.__tableCell.isConnected})`);
  evaluate(`(()=>{window.typora.command('heading1');return true})()`);
  check('Table focus intercepts block formatting',`({ok:window.typora.getMarkdown()===${JSON.stringify(source.replace('first','alpha中文'))}})`);
  evaluate(`(()=>{window.typora.editor.dispatch({changes:{from:0,insert:'PREFIX\\n\\n'}});return true})()`);
  run('keyboard','inserttext','Q');
  check('Edits above table refresh its source position',`({ok:window.typora.getMarkdown()===${JSON.stringify('PREFIX\n\n'+source.replace('first','alpha中文Q'))}})`);
  run('press','Meta+z');
  check('Undo refreshes source and visible cell together',`(()=>{const text=window.typora.getMarkdown();const row=text.split(String.fromCharCode(10)).find(l=>l.includes('**bold**'));const cell=document.querySelector('.lp-cell[data-row="1"][data-col="1"]').textContent;return {ok:!!row&&cell===row.split('|')[2].trim(),text,cell}})()`);
  run('press','Meta+Shift+z');
  check('Redo restores edited source and visible cell',`({ok:window.typora.getMarkdown().includes('alpha中文Q')&&document.querySelector('.lp-cell[data-row="1"][data-col="1"]').textContent==='alpha中文Q'})`);
  run('click','.lp-cell[data-row="2"][data-col="1"]');
  run('press','Tab');
  check('Last-cell Tab adds row and focuses its first cell',`({ok:document.querySelectorAll('.lp-table-grid tbody tr').length===3&&document.activeElement?.dataset.row==='3'&&document.activeElement?.dataset.col==='0',row:document.activeElement?.dataset.row,col:document.activeElement?.dataset.col})`);
  run('press','Meta+Enter');
  check('Command Enter inserts a data row',`({ok:document.querySelectorAll('.lp-table-grid tbody tr').length===4})`);
  run('press','Meta+Shift+Backspace');
  check('Command Shift Backspace removes one data row',`({ok:document.querySelectorAll('.lp-table-grid tbody tr').length===3})`);
  check('Structural edits preserve surrounding document',`({ok:window.typora.getMarkdown().startsWith('PREFIX\\n\\n# Tables\\n\\nOUTSIDE_BEFORE\\n\\n')&&window.typora.getMarkdown().endsWith('\\n\\nOUTSIDE_AFTER\\n')})`);
  run('click','.lp-cell[data-row="1"][data-col="1"]');
  run('press','End');
  run('press','Enter');
  run('keyboard','inserttext','NEXT');
  check('Cell line break stays inside the Markdown table',`({ok:window.typora.getMarkdown().includes('<br>NEXT')&&document.querySelectorAll('.lp-table-grid tbody tr').length===3&&window.typora.getMarkdown().endsWith('\\n\\nOUTSIDE_AFTER\\n')})`);
  run('click','.lp-table-toolbar button[title="Align center"]');
  check('Alignment toolbar updates source and rendered column',`(()=>{const lines=window.typora.getMarkdown().split(String.fromCharCode(10)).filter(l=>l.startsWith('|'));const align=lines[1].split('|')[2].trim();return {ok:align.startsWith(':')&&align.endsWith(':')&&document.querySelector('.lp-cell[data-row="1"][data-col="1"]').style.textAlign==='center'}})()`);
  run('fill','.lp-table-toolbar input[title="Columns"]','3');
  run('press','Enter');
  check('Resize control updates all rows and preserves outside text',`({ok:document.querySelectorAll('.lp-table-grid tbody tr:first-child .lp-cell').length===3&&window.typora.getMarkdown().includes('OUTSIDE_BEFORE')&&window.typora.getMarkdown().endsWith('\\n\\nOUTSIDE_AFTER\\n')})`);
  run('hover','.lp-table-grid');
  run('drag','.lp-row-grip[data-row="0"]','.lp-row-grip[data-row="1"]');
  check('Dragging a row changes the actual table',`({ok:document.querySelector('.lp-table-grid tbody tr:first-child .lp-cell[data-col="0"]').textContent==='中文'})`);
  run('hover','.lp-table-grid');
  run('drag','.lp-col-handle[data-col="0"]','.lp-col-handle[data-col="2"]');
  check('Dragging a column changes the actual table',`({ok:document.querySelector('.lp-cell[data-row="0"][data-col="2"]').textContent==='Name'})`);
} catch(e){results.push({name:'Table UI interaction',passed:false,detail:e.message});}
writeFileSync('evidence/table-browser-verification.json',JSON.stringify({date:new Date().toISOString(),results},null,2));
for(const r of results)console.log(`${r.passed?'PASS':'FAIL'} ${r.name}`);
if(results.some(r=>!r.passed))process.exitCode=1;
